"""Encode optimized catalog artwork as data URIs, compatible with the existing native APK."""
from pathlib import Path
from PIL import Image
import base64,io,json
root=Path(__file__).resolve().parents[1]
images={}
for file in sorted((root/'assets/catalog').glob('*.png')):
 image=Image.open(file).convert('RGB');image.thumbnail((512,768))
 output=io.BytesIO();image.save(output,format='JPEG',quality=84,optimize=True)
 images[file.stem]='data:image/jpeg;base64,'+base64.b64encode(output.getvalue()).decode()
assert len(images)==10
(root/'src/data/catalog-images.ts').write_text('/* Generated by scripts/bake-catalog.py. */\nimport type { Universe } from "../domain/types";\nexport const catalogImages: Record<Universe, string> = '+json.dumps(images,separators=(',',':'))+';\n')
print('Catalog artwork encoded:',len(images))
